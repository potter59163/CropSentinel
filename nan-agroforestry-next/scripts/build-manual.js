const t = (text, opts = {}) => new TextRun({
  text, font: FONT, size: opts.size || BODY, bold: opts.bold || false,
  color: opts.color || INK, italics: opts.italics || false,
});

const p = (text, opts = {}) => new Paragraph({
  alignment: opts.align || AlignmentType.THAI_DISTRIBUTE,
  spacing: { after: opts.after === undefined ? 120 : opts.after, line: opts.line || 300 },
  indent: opts.indent,
  children: Array.isArray(text) ? text : [t(text, opts)],
});

/** Body paragraph with a first-line indent, the Thai report convention. */
const para = (text, opts = {}) => p(text, { ...opts, indent: { firstLine: 720 } });

const bullet = (text, opts = {}) => new Paragraph({
  bullet: { level: opts.level || 0 },
  spacing: { after: 80, line: 300 },
  children: Array.isArray(text) ? text : [t(text, { size: opts.size || BODY })],
});

